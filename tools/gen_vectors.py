#!/usr/bin/env python3
"""Regenerate tests/vectors/decode.tsv from the corpus with aprslib as the oracle.

aprslib (ref/aprs-python, GPL-2.0-or-later, commit c2a0f18) is run, never linked or copied.
Each row is ``line<TAB>field=value<TAB>...``; the C test checks only the listed fields:

  fmt    position format (uncompressed, compressed, mic-e, object, message, status, ...)
  lat, lon, course, speed (km/h), alt (m), sym (table+code), name, alive, msgcap,
  to, text, msgno, acked, status, temp, hum, press, rain1h, gust

Where aprslib and this core differ on purpose, ``tests/vectors/overrides.tsv`` holds the
expected values (with the reason); unsupported aprslib formats (items, telemetry, NMEA) come
from there too.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ref" / "aprs-python"))
import aprslib  # noqa: E402

FMT = {"uncompressed": "position", "compressed": "position", "mic-e": "position",
       "object": "object", "message": "message", "status": "status", "wx": "weather",
       "bulletin": "bulletin", "group-bulletin": "bulletin"}


def fields(d):
    out = {}
    fmt = d.get("format")
    if fmt in FMT:
        out["type"] = FMT[fmt]
    if fmt == "message" and d.get("response") in ("ack", "rej"):
        out["type"] = d["response"]
        out["acked"] = d.get("msgNo", "")
        return out
    for k, key in (("latitude", "lat"), ("longitude", "lon")):
        if k in d:
            out[key] = round(d[k], 5)
    if "symbol" in d and "symbol_table" in d:
        out["sym"] = d["symbol_table"] + d["symbol"]
    if "object_name" in d:
        out["name"] = d["object_name"].rstrip()
        out["alive"] = int(d["alive"])
    if "messagecapable" in d:
        out["msgcap"] = int(d["messagecapable"])
    if fmt in ("message",):
        out["to"] = d.get("addresse", "")
        out["text"] = d.get("message_text", "")
        if d.get("msgNo"):
            out["msgno"] = d["msgNo"]
    if fmt == "status":
        out["status"] = d.get("status", "")
    if d.get("symbol") != "_":
        if "course" in d:
            out["course"] = d["course"] % 360
        if "speed" in d:
            out["speed"] = round(d["speed"], 2)
    if "altitude" in d:
        out["alt"] = round(d["altitude"], 2)
    wx = d.get("weather") or {}
    for k, key in (("temperature", "temp"), ("humidity", "hum"), ("pressure", "press"),
                   ("rain_1h", "rain1h")):
        if k in wx:
            out[key] = round(wx[k], 2)
    return out


def main():
    corpus = ROOT / "tests" / "vectors" / "corpus.txt"
    overrides = {}
    path = ROOT / "tests" / "vectors" / "overrides.tsv"
    for row in path.read_text().splitlines():
        if row and not row.startswith("#"):
            parts = row.split("\t")
            overrides[parts[0]] = dict(p.split("=", 1) for p in parts[1:] if "=" in p
                                       and not p.startswith("why="))
    rows = []
    for line in corpus.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        try:
            got = fields(aprslib.parse(line))
        except Exception as exc:  # unsupported format, or garbage
            got = {"oracle": type(exc).__name__}
        for k, v in overrides.get(line, {}).items():
            if v == "-":
                got.pop(k, None)      # an aprslib value this core rejects on purpose
            else:
                got[k] = v
        rows.append(line + "".join(f"\t{k}={v}" for k, v in sorted(got.items())))
    (ROOT / "tests" / "vectors" / "decode.tsv").write_text(
        "# generated by tools/gen_vectors.py (aprslib c2a0f18 + overrides.tsv); do not edit\n"
        + "\n".join(rows) + "\n")
    print(json.dumps({"rows": len(rows)}))


if __name__ == "__main__":
    main()
